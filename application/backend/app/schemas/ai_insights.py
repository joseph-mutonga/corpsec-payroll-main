from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    role: str = Field(..., description="Role of the author: 'user' or 'model'")
    content: str = Field(..., description="Content of the message")


class AIInsightsRequest(BaseModel):
    prompt: str = Field(..., min_length=1, max_length=2000, description="Administrator's natural language inquiry")
    history: Optional[List[ChatMessage]] = Field(default=[], description="Previous conversation messages for context")
    include_telemetry: bool = Field(default=True, description="Whether to ground query with real-time system metrics")


class AIInsightsResponse(BaseModel):
    status: str = Field(default="success", description="Response status: success, key_required, or error")
    answer: str = Field(..., description="Data-grounded answer generated by Gemini Analyst")
    model_used: str = Field(..., description="Gemini model invoked, e.g. gemini-3.5-flash-lite")
    timestamp: str = Field(..., description="ISO 8601 timestamp of analysis")
    grounding_metrics_summary: Optional[Dict[str, Any]] = Field(default=None, description="Summary of metrics used for grounding")
    has_api_key: bool = Field(default=True, description="Indicates whether a valid GEMINI_API_KEY is configured")
    category: Optional[str] = Field(default=None, description="Classified question category: SIMPLE, WORKFORCE, PAYROLL, MANAGEMENT, COMPLEX")
    db_query_time_ms: Optional[float] = Field(default=None, description="Database retrieval duration in milliseconds")
    gemini_latency_ms: Optional[float] = Field(default=None, description="Gemini generation duration in milliseconds")
    total_duration_ms: Optional[float] = Field(default=None, description="Total end-to-end request latency in milliseconds")


class TelemetrySnapshotResponse(BaseModel):
    timestamp: str
    host_telemetry: Dict[str, Any]
    database_telemetry: Dict[str, Any]
    error_rates: Dict[str, Any]
    operations_telemetry: Dict[str, Any]
    financial_telemetry: Dict[str, Any]
    active_users: Dict[str, Any]
    recent_audit_actions: List[Dict[str, Any]]
    guards_register: Optional[List[Dict[str, Any]]] = Field(default=None, description="Complete register of all guards")
    supervisors_register: Optional[List[Dict[str, Any]]] = Field(default=None, description="Complete register of all supervisors")
    client_sites_register: Optional[List[Dict[str, Any]]] = Field(default=None, description="Complete register of client sites")
    shifts_register: Optional[List[Dict[str, Any]]] = Field(default=None, description="Complete register of shifts")
    client_contracts_register: Optional[List[Dict[str, Any]]] = Field(default=None, description="Active client contracts")
    recent_incidents_register: Optional[List[Dict[str, Any]]] = Field(default=None, description="Recent incident logs")
